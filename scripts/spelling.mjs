const longestFirst = Object.keys(FIXES).sort((a, b) => b.length - a.length)
const WRONG_SPELLING = new RegExp(`(?<!\\p{L})(?:${longestFirst.map(RegExp.escape).join('|')})(?!\\p{L})`, 'gu')

const TEXT_NODE = /(?<=>)[^<]+(?=<)/g

export const fixSpelling = (xml) =>
  xml.replace(TEXT_NODE, (text) => text.replace(WRONG_SPELLING, (wrong) => FIXES[wrong]))
