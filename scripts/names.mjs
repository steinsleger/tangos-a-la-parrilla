// One surname shared by two people, so each part means nothing alone.
const SHARED_SURNAME = new Set(['A. y H. Manzi', 'J. y L. Servidio', 'T. y M. Lespés'])

const joinNames = (names) => (names.length < 2 ? names[0] : `${names.slice(0, -1).join(', ')} y ${names.at(-1)}`)

export function fullNames(credit) {
  if (SHARED_SURNAME.has(credit)) return credit

  const names = creditParts(credit).filter((_, index) => index % 2 === 0)
  return names.some((name) => name in FULL_NAMES) ? joinNames(names.map((name) => FULL_NAMES[name] ?? name)) : credit
}
